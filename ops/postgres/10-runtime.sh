#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=runtime_password="$DOCKFLOW_DB_PASSWORD" <<'SQL'
CREATE ROLE dockflow LOGIN PASSWORD :'runtime_password';
REVOKE ALL ON DATABASE dockflow FROM PUBLIC;
GRANT CONNECT ON DATABASE dockflow TO dockflow;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO dockflow;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO dockflow;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO dockflow;
SQL
